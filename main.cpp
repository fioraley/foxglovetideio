#include <string>
#include <vector>

void sum_range() {
    int acc = 0;
    for (int i = 10; i <= 20; ++i) acc += i;
    (void)acc;
}

void digit_count() {
    int n = 1234567;
    int digits = 0;
    while (n > 0) { digits += 1; n /= 10; }
    (void)digits;
}

void char_frequency() {
    std::string text = "banana";
    int count = 0;
    for (std::size_t i = 0; i < text.size(); ++i) {
        if (text[i] == 'a') count += 1;
    }
    (void)count;
}

void least_multiple() {
    int a = 6, b = 8;
    int x = a, y = b;
    while (y != 0) {
        int t = x % y;
        x = y;
        y = t;
    }
    int lcm = a / x * b;
    (void)lcm;
}

extern "C" int brisk_boulder();
extern void noble_crescent();
extern void silver_summit();
extern void mellow_signal();
extern void silver_grove();

int main() {
    sum_range();
    digit_count();
    char_frequency();
    least_multiple();
    noble_crescent();
    silver_summit();
    mellow_signal();
    silver_grove();
    return brisk_boulder();
}
